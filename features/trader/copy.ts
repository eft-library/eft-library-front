export function getTraderName(
  trader: LocalizedName & { normalized_name: string },
  locale: Locale,
) {
  if (locale === "ko") {
    if (trader.normalized_name === "ragman") return "레그맨";
    if (trader.normalized_name === "ref") return "레프";
  }
  return pickLocalizedText(trader, locale);
}

