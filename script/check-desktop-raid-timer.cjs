const assert = require("node:assert/strict");
const fs = require("node:fs");
const vm = require("node:vm");
const ts = require("typescript");
const code = ts.transpileModule(fs.readFileSync("lib/websocket/raid-state.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 } }).outputText;
const moduleRef = { exports: {} };
vm.runInNewContext(`(function(module,exports){${code}\n})`)(moduleRef, moduleRef.exports);
const { isRaidState, getAutomaticRaidTimer, formatRaidRemaining } = moduleRef.exports;
const observed = Date.parse("2026-10-19T00:00:00Z");
const state = { map: "woods", started_at: "2026-10-18T23:59:00Z", is_active: true, transit_count: 0, session_id: "a".repeat(64), timer_observed_at: new Date(observed).toISOString(), raid_ends_at: new Date(observed + 2100000).toISOString() };
assert(isRaidState(state));
assert.equal(getAutomaticRaidTimer(state, "woods", observed + 65000).remainingSeconds, 2035);
assert.equal(getAutomaticRaidTimer({ ...state }, "woods", observed + 120000).remainingSeconds, 1980);
assert.equal(getAutomaticRaidTimer(state, "woods", observed + 2200000).remainingSeconds, 0);
assert.equal(getAutomaticRaidTimer(state, "customs", observed), null);
assert.equal(getAutomaticRaidTimer({ ...state, is_active: false }, "woods", observed), null);
assert.equal(getAutomaticRaidTimer({ ...state, session_id: "b".repeat(64), timer_observed_at: null, raid_ends_at: null }, "woods", observed), null);
const legacy = { map: "woods", started_at: state.started_at, is_active: true, transit_count: 0 };
assert(isRaidState(legacy)); assert.equal(getAutomaticRaidTimer(legacy, "woods", observed), null);
for (const changes of [{ raid_ends_at: null }, { session_id: "bad" }, { timer_observed_at: "2026-10-19T00:00:00" }, { raid_ends_at: state.timer_observed_at }, { map: "unknown-map" }]) assert.equal(isRaidState({ ...state, ...changes }), false);
assert.equal(formatRaidRemaining(2035), "33:55");
console.log("PASS absolute deadline, delayed delivery, reconnect, expiry, map/session/null reset, legacy and invalid payloads");
